-- Keep text identifiers and epoch-millisecond session expiry compatible with SQLite.
CREATE TABLE public.users (
  id TEXT PRIMARY KEY,
  email TEXT UNIQUE NOT NULL,
  password TEXT NOT NULL
);

CREATE TABLE public.tasks (
  id TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES public.users(id),
  title TEXT NOT NULL,
  completed BOOLEAN NOT NULL DEFAULT FALSE,
  -- A future import can preserve SQLite rowid here and reset the sequence.
  position BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE NOT NULL
);

CREATE INDEX tasks_owner ON public.tasks(user_id);

CREATE TABLE public.sessions (
  hash TEXT PRIMARY KEY,
  user_id TEXT NOT NULL REFERENCES public.users(id),
  expires BIGINT NOT NULL
);

CREATE INDEX sessions_expiry ON public.sessions(expires);
